/**
 * "How it works" as a horizontal image sequence.
 * Wide screens with motion allowed: the section pins and vertical scrolling moves the panels sideways
 * (travel measured from the real track width, recalculated on resize and image load).
 * Everywhere else: a native, swipeable scroll-snap row with previous/next controls.
 */
export function Story() {
  const sectionRef = useRef<HTMLElement>(null);
  const trackRef = useRef<HTMLOListElement>(null);
  const triggerRef = useRef<ScrollTrigger | null>(null);
  const [active, setActive] = useState(0);
  const [pinned, setPinned] = useState(false);
  // Set to false when the viewport is too short for the pinned panels to hold their text; the row is used instead.
  const [pinFits, setPinFits] = useState(true);

  useEffect(() => {
    gsap.registerPlugin(ScrollTrigger);
    const mm = gsap.matchMedia();
    if (!pinFits) return () => mm.revert();
    mm.add("(min-width: 1024px) and (min-height: 760px) and (prefers-reduced-motion: no-preference)", () => {
      const track = trackRef.current!;
      const section = sectionRef.current!;
      setPinned(true);
      const travel = () => Math.max(0, track.scrollWidth - track.clientWidth);
      const headerOffset = () => document.querySelector("header")?.getBoundingClientRect().height ?? 0;
      const tween = gsap.to(track, {
        x: () => -travel(),
        ease: "none",
        scrollTrigger: {
          trigger: section,
          start: () => `top ${headerOffset()}`,
          end: () => `+=${travel()}`,
          pin: true,
          scrub: 0.5,
          invalidateOnRefresh: true,
          onUpdate: (self) => setActive(Math.round(self.progress * (PANELS.length - 1))),
        },
      });
      triggerRef.current = tween.scrollTrigger ?? null;
      const ro = new ResizeObserver(() => ScrollTrigger.refresh());
      ro.observe(track);
      // Layout settles after the switch to pinned mode and font loading. If any panel's content is
      // taller than the space the pin leaves, fall back to the scrollable row rather than clip or overlap text.
      const overflows = () => (Array.from(track.children) as HTMLElement[]).some((li) => li.scrollHeight > li.clientHeight + 1);
      requestAnimationFrame(() => {
        if (overflows()) setPinFits(false);
        else ScrollTrigger.refresh();
      });
      document.fonts?.ready.then(() => ScrollTrigger.refresh());
      return () => {
        ro.disconnect();
        triggerRef.current = null;
        tween.scrollTrigger?.kill();
        tween.kill();
        gsap.set(track, { clearProps: "transform" });
        setPinned(false);
      };
    });
    return () => mm.revert();
  }, [pinFits]);

  function onTrackScroll() {
    if (pinned) return;
    const t = trackRef.current!;
    const items = Array.from(t.children) as HTMLElement[];
    const left = t.scrollLeft;
    let best = 0;
    items.forEach((el, i) => {
      if (Math.abs(el.offsetLeft - t.offsetLeft - left) < Math.abs(items[best].offsetLeft - t.offsetLeft - left)) best = i;
    });
    setActive(best);
  }

  function go(i: number) {
    const idx = Math.max(0, Math.min(PANELS.length - 1, i));
    const st = triggerRef.current;
    if (pinned && st) {
      window.scrollTo({ top: st.start + ((st.end - st.start) * idx) / (PANELS.length - 1), behavior: "smooth" });
      return;
    }
    const t = trackRef.current!;
    const el = t.children[idx] as HTMLElement;
    const reduce = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    t.scrollTo({ left: el.offsetLeft - t.offsetLeft - parseFloat(getComputedStyle(t).paddingLeft), behavior: reduce ? "auto" : "smooth" });
  }

  return (
    <section
      id="how-it-works"
      ref={sectionRef}
      aria-labelledby="story-title"
      className={`relative overflow-hidden border-y border-line bg-raised ${pinned ? "flex h-[calc(100svh-4.5rem)] flex-col" : ""}`}
    >
      <div className={`wrap flex flex-col gap-5 sm:flex-row sm:items-end sm:justify-between ${pinned ? "pt-7 pb-5" : "pt-16 pb-8 lg:pt-24"}`}>
        <div>
          <p className="eyebrow">How it works</p>
          <h2 id="story-title" className={`mt-4 max-w-[16ch] ${pinned ? "t-2" : "t-1"}`}>From invitation to decision.</h2>
        </div>
        <div className="flex items-center gap-4">
          <p className="font-display text-lg tabular-nums" aria-live="polite">
            <span className="font-semibold">{String(active + 1).padStart(2, "0")}</span>
            <span className="text-muted"> / {String(PANELS.length).padStart(2, "0")}</span>
            <span className="sr-only">: {PANELS[active].kicker}</span>
          </p>
          <div className="flex">
            <button type="button" className="inline-flex size-12 items-center justify-center border border-ink hover:bg-ink hover:text-bg disabled:opacity-30" onClick={() => go(active - 1)} disabled={active === 0} aria-label="Previous step">
              <BackIcon className="size-5" />
            </button>
            <button type="button" className="-ml-px inline-flex size-12 items-center justify-center border border-ink hover:bg-ink hover:text-bg disabled:opacity-30" onClick={() => go(active + 1)} disabled={active === PANELS.length - 1} aria-label="Next step">
              <ArrowIcon className="size-5" />
            </button>
          </div>
        </div>
      </div>

      <div className="wrap" aria-hidden>
        <div className="h-px bg-line">
          <div className="h-px origin-left bg-ink transition-transform duration-300" style={{ transform: `scaleX(${(active + 1) / PANELS.length})` }} />
        </div>
      </div>

      <ol
        ref={trackRef}
        onScroll={onTrackScroll}
        className={`story-track relative flex gap-5 px-[clamp(1rem,4vw,3.5rem)] lg:gap-8 ${
          pinned ? "min-h-0 flex-1 py-6" : "snap-x snap-mandatory overflow-x-auto scroll-px-[clamp(1rem,4vw,3.5rem)] pt-8 pb-6"
        }`}
        aria-label="Steps"
        // Keyboard users can scroll the swipeable row with arrow keys; not needed once scrolling is pinned.
        tabIndex={pinned ? undefined : 0}
      >
        {PANELS.map((p, i) => (
          <li
            key={p.kicker}
            className={`grid flex-none snap-start grid-cols-[minmax(0,1fr)] grid-rows-[auto_1fr] gap-6 bg-bg pb-6 lg:grid-cols-[minmax(0,1.2fr)_minmax(0,1fr)] lg:grid-rows-1 lg:gap-0 lg:pb-0 [&>*]:min-w-0 ${
              pinned ? "h-full w-[min(1120px,80vw)]" : "w-[86%] sm:w-[72%] lg:w-[min(1120px,80vw)] lg:min-h-[min(600px,72svh)]"
            }`}
            aria-label={`Step ${i + 1} of ${PANELS.length}: ${p.kicker}`}
          >
            <div className="relative aspect-[4/5] min-h-0 sm:aspect-[4/3] lg:aspect-auto">{p.visual}</div>
            <div className="flex flex-col px-4 sm:px-5 lg:justify-between lg:p-9 xl:p-11">
              <p className="font-display text-[3rem] font-semibold leading-none tracking-[-0.05em] text-accent lg:text-[4.25rem]">{String(i + 1).padStart(2, "0")}</p>
              <div className="mt-4 lg:mt-0">
                <p className="eyebrow plain">{p.kicker}</p>
                <h3 className="t-3 mt-3 max-w-[22ch]">{p.title}</h3>
                <p className="mt-4 max-w-[46ch] leading-relaxed text-ink-2">{p.body}</p>
              </div>
            </div>
          </li>
        ))}
      </ol>
      {!pinned ? null : <p className="sr-only">Scroll down to move through the steps, or use the previous and next buttons.</p>}
      <p className={`wrap photo-credit ${pinned ? "pb-8" : "pb-16 lg:pb-24"}`}>
        The invitation panel is illustrative. The outfit and both YouCam outputs are from actual recorded WearCheck tests on 1 November 2026, not a fresh generation. Clothing and shoe previews are separate operations. Source: Brooke Cagle, <a className="underline" href="https://commons.wikimedia.org/wiki/File:Man_in_front_of_brick_wall_(Unsplash).jpg">CC0 source record</a>; reference credits and full comparisons are on <a href="/demo" className="underline">the demo page</a>. The clothing preview retains a conflicting white layer. Editorial invitation image: {EDITORIAL.colonnade.credit.replace("Editorial photo · ", "")}.
      </p>
    </section>
  );
}
